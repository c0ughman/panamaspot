def config():
    return json.loads(CONFIG.read_text())


def _e(s):
    return html.escape(s, quote=True)


def _search_icon():
    return ('<svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" aria-hidden="true">'
            '<circle cx="11" cy="11" r="7"/><path d="m20 20-3.5-3.5"/></svg>')


def _inner(kind, items):
    if kind == "dest":
        return '<div class="mm-dest">' + "".join(
            f'<a href="{_e(i["href"])}"><img alt="" loading="lazy" src="{_e(i["photo"])}"/><b>{_e(i["name"])}</b>'
            + (f'<small>{_e(i["note"])}</small>' if i.get("note") else "") + "</a>" for i in items) + "</div>"
    return '<ul class="mm-list">' + "".join(
        f'<li><a href="{_e(i["href"])}"><img alt="" loading="lazy" src="{_e(i["photo"])}"/><span>{_e(i["name"])}</span></a></li>' for i in items) + "</ul>"


def nav_html(lang, en_href, es_href):
    """The whole <div class="wrap nav"> block for a page in `lang` whose EN and ES versions live at en_href / es_href."""
    M = config()[lang]
    home = "/es" if lang == "es" else "/"
    desk = '<nav class="links mm" aria-label="Main">' + "".join(
        f'<div class="mm-item"><button type="button" class="mm-btn" aria-expanded="false" aria-controls="mm-{i}">{_e(g["label"])}</button>'
        f'<div class="mm-panel mm-p-{g["kind"]}" id="mm-{i}" hidden>{_inner(g["kind"], g["items"])}</div></div>'
        for i, g in enumerate(M["groups"])) + "</nav>"
    sheet = "".join(f'<section><h3>{_e(g["label"])}</h3>{_inner(g["kind"], g["items"])}</section>' for g in M["groups"])
    mob = (f'<button type="button" class="mm-burger glass" aria-expanded="false" aria-controls="mm-sheet" aria-label="{_e(M["menu"])}"><i></i><i></i></button>'
           f'<div class="mm-sheet" id="mm-sheet" hidden><div class="mm-sheet-in">{sheet}</div></div>')
    search = f'<a class="search glass" href="{home}#cat-regions" data-search aria-haspopup="dialog">{_search_icon()}<span>{_e(M["search"])}</span></a>'
    other, olang = (es_href, "es") if lang == "en" else (en_href, "en")
    switch = (f'<a class="lang glass" href="{_e(other)}" hreflang="{olang}" aria-label="{"Español" if olang == "es" else "English"}">'
              f'<span{" class=\"on\"" if lang == "en" else ""}>EN</span><span{" class=\"on\"" if lang == "es" else ""}>ES</span></a>')
    return (f'<div class="wrap nav"><a class="logo" href="{home}">Panam<span class="a">á</span><i class="pd"></i></a>{desk}'
            f'<div class="tools">{search}{mob}{switch}</div></div>')


