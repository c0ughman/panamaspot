def css_block():
    return f"{CSS_M[0]}<style>{CSS}</style>{CSS_M[1]}"


def js_block():
    return f"{JS_M[0]}{JS}{JS_M[1]}"


def _block(h, start):
    """The balanced <div …>…</div> that begins at `start`."""
    i = h.index(start); depth = 0
    for m in re.finditer(r"<div\b|</div>", h[i:]):
        depth += 1 if m[0] == "<div" else -1
        if depth == 0:
            return i, i + m.end()
    raise ValueError("unbalanced nav block")


def _twins(h, rel):
    """(en_href, es_href) for the page at public/<rel>, read from its current language switch."""
    lang = "es" if rel.startswith("es/") else "en"
    me = "/" + rel[:-5]
    other = None
    m = re.search(r'<a class="lang glass" href="([^"]+)"', h)
    if m:
        other = html.unescape(m[1])
    else:
        m = re.search(r'<span class="lang glass">(.*?)</span>', h, re.S)
        if m:
            for a in re.findall(r"<a\b[^>]*>", m[1]):
                if 'class="on"' not in a:
                    other = re.search(r'href="([^"]+)"', a)[1]
    other = other or ("/" if lang == "es" else "/es")
    return (me, other) if lang == "en" else (other, me)


def strip_assets(h):
    for a, b in (CSS_M, JS_M):
        h = re.sub(re.escape(a) + r".*?" + re.escape(b) + r"\n?", "", h, flags=re.S)
    return h


def apply(h, rel):
    lang = "es" if rel.startswith("es/") else "en"
    en, es = _twins(h, rel)
    i, j = _block(h, '<div class="wrap nav">')
    h = h[:i] + nav_html(lang, en, es) + h[j:]
    h = strip_assets(h)
    h = h.replace("</head>", css_block() + "\n</head>", 1)
    return h.replace("</body>", js_block() + "\n</body>", 1)


if __name__ == "__main__":
    dry = "--dry" in sys.argv
    n = total = 0
    for f in sorted(PUB.glob("articles/*.html")) + sorted(PUB.glob("es/articles/*.html")):
        h = f.read_text()
        if '<div class="wrap nav">' not in h:
            continue
        total += 1
        new = apply(h, str(f.relative_to(PUB)))
        if new != h:
            n += 1
            if not dry:
                f.write_text(new)
    print(("would change" if dry else "changed"), n, "of", total, "pages")
